const FOLIO_FV_COUNT = 7;
const FOLIO_FV_CATEGORIES = ["system", "app", "web", "game", "python"];

export function portfolioFvFrames() {
  const pools = FOLIO_FV_CATEGORIES.map((categoryId) =>
    pickStable(itemsInCategory(categoryId), FOLIO_FV_COUNT, `folio-fv:${categoryId}`)
  );
  const chosen = [];
  for (let round = 0; chosen.length < FOLIO_FV_COUNT; round += 1) {
    let added = false;
    for (const pool of pools) {
      if (chosen.length >= FOLIO_FV_COUNT) break;
      const item = pool[round];
      if (!item) continue;
      chosen.push(item);
      added = true;
    }
    if (!added) break;
  }
  return chosen.map((item) => ({
    src: item.images[0],
    title: item.title,
    label: item.label || item.title
  }));
}
