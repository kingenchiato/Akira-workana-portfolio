function stableRank(seed, id) {
  let hash = 2166136261;
  const text = `${seed}\0${id}`;
  for (let index = 0; index < text.length; index += 1) {
    hash ^= text.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

function pickStable(items, count, seed) {
  return [...items]
    .filter((item) => item.images?.[0])
    .sort((a, b) => stableRank(seed, a.id) - stableRank(seed, b.id) || a.id.localeCompare(b.id))
    .slice(0, count);
}

