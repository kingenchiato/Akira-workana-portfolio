export function presentWork(item, lang) {
  const row = briefs[item.id];
  if (row) {
    const pair = row[lang] || row.en;
    return { title: pair[0], text: pair[1] };
  }
  if (item.category === "logo") {
    return {
      title: item.title,
      text:
        lang === "ja"
          ? item.summary
          : lang === "pt"
            ? "Marca desenhada à mão."
            : "Hand-drawn identity mark."
    };
  }
  if (item.category === "card") {
    return {
      title: item.title,
      text: lang === "ja" ? item.summary : lang === "pt" ? "Cartão de visita." : "Business card."
    };
  }
  return { title: item.title, text: item.summary || "" };
}
